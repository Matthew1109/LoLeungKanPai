import { DB_VERSION, type Bar, type DrinkEntry, type Tag } from '../db/schema';
import { isValidDayKey } from '../utils/dates';
import { nameKey } from '../utils/normalise';
import { isValidDateTime, validateEntry } from '../utils/entryValidation';
import { ZipError, ZipReader, type ZipEntry } from './zip';

export const BACKUP_APP = 'LoLeungKanPai';
export const BACKUP_FORMAT_VERSION = 1;

export interface BackupManifest {
  app: string;
  formatVersion: number;
  dbSchemaVersion: number;
  appVersion: string;
  createdAt: string;
  counts: { entries: number; tags: number; photos: number };
  dateRange: { first: string | null; last: string | null };
}

export interface BackupPhotoMeta {
  id: string;
  mime: string;
  size: number;
  width: number;
  height: number;
  createdAt: string;
}

export interface BackupData {
  entries: DrinkEntry[];
  tags: Tag[];
  /** The Bar library. Backups made before it existed have no such list in data.json; reading one yields []. */
  bars: Bar[];
  photos: BackupPhotoMeta[];
}

export type BackupErrorCode =
  | 'NOT_A_BACKUP' // not a ZIP, or not one of ours
  | 'UNREADABLE' // a ZIP layout we do not read
  | 'NEWER_VERSION' // made by a newer app
  | 'DAMAGED' // CRC / size / JSON broken
  | 'INVALID' // content breaks the rules
  | 'MISSING_PHOTO';

export class BackupFormatError extends Error {
  constructor(readonly code: BackupErrorCode, readonly detail: string = '') {
    super(`Backup ${code}${detail ? `: ${detail}` : ''}`);
    this.name = 'BackupFormatError';
  }
}

export const photoFileName = (id: string): string => `photos/${id}.jpg`;
/** Ids are generated by us (UUIDs); anything else would be an odd file name, so it is rejected up front. */
const SAFE_ID = /^[A-Za-z0-9_-]{1,64}$/;
const MAX_MANIFEST = 1 << 20;
const MAX_DATA = 64 << 20;
const MAX_PHOTO = 40 << 20;
const MAX_ROWS = 200_000;

export interface OpenedBackup {
  manifest: BackupManifest;
  data: BackupData;
  /** Verified lookup of a photo file, by its id in the backup. */
  readPhoto(id: string): Promise<Uint8Array>;
  photoBytes: number;
}

const isRecord = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);
const isStr = (v: unknown): v is string => typeof v === 'string';
const isNum = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v);

/** Names as stored, minus Finder junk, and minus one wrapping folder (a backup re-zipped on a Mac). */
export function listBackupFiles(entries: readonly ZipEntry[]): Map<string, ZipEntry> {
  const files = entries.filter((e) => !e.name.endsWith('/') && !e.name.startsWith('__MACOSX/') && e.name.split('/').pop() !== '.DS_Store');
  let prefix = '';
  if (files.length > 0 && !files.some((e) => e.name === 'manifest.json')) {
    const first = files[0].name.split('/')[0];
    if (files.every((e) => e.name.startsWith(`${first}/`))) prefix = `${first}/`;
  }
  const out = new Map<string, ZipEntry>();
  for (const e of files) out.set(e.name.slice(prefix.length), e);
  return out;
}

function parseJson(bytes: Uint8Array, what: string): unknown {
  try {
    return JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes));
  } catch {
    throw new BackupFormatError('DAMAGED', `${what} cannot be read`);
  }
}

export function parseManifest(raw: unknown): BackupManifest {
  if (!isRecord(raw) || raw.app !== BACKUP_APP) throw new BackupFormatError('NOT_A_BACKUP', 'manifest');
  const { formatVersion, dbSchemaVersion, counts, dateRange } = raw;
  if (!isNum(formatVersion) || !Number.isInteger(formatVersion) || formatVersion < 1) throw new BackupFormatError('INVALID', 'formatVersion');
  if (formatVersion > BACKUP_FORMAT_VERSION) throw new BackupFormatError('NEWER_VERSION', `format ${formatVersion}`);
  if (!isNum(dbSchemaVersion) || dbSchemaVersion < 1) throw new BackupFormatError('INVALID', 'dbSchemaVersion');
  if (dbSchemaVersion > DB_VERSION) throw new BackupFormatError('NEWER_VERSION', `database ${dbSchemaVersion}`);
  if (!isValidDateTime(raw.createdAt)) throw new BackupFormatError('INVALID', 'createdAt');
  if (!isRecord(counts) || !isNum(counts.entries) || !isNum(counts.tags) || !isNum(counts.photos)) throw new BackupFormatError('INVALID', 'counts');
  const range = isRecord(dateRange) ? dateRange : {};
  return {
    app: BACKUP_APP,
    formatVersion,
    dbSchemaVersion,
    appVersion: isStr(raw.appVersion) ? raw.appVersion : '',
    createdAt: raw.createdAt,
    counts: { entries: counts.entries, tags: counts.tags, photos: counts.photos },
    dateRange: { first: isStr(range.first) ? range.first : null, last: isStr(range.last) ? range.last : null },
  };
}

function checkTag(raw: unknown, index: number): Tag {
  const bad = (what: string) => new BackupFormatError('INVALID', `tag ${index + 1}: ${what}`);
  if (!isRecord(raw)) throw bad('not an object');
  if (!isStr(raw.id) || raw.id.length === 0) throw bad('id');
  if (!isStr(raw.name) || raw.name.trim().length === 0) throw bad('name');
  const { category, isArchived, createdAt, updatedAt } = raw;
  if (category !== 'BASE_SPIRIT' && category !== 'INGREDIENT') throw bad('category');
  if (typeof isArchived !== 'boolean') throw bad('isArchived');
  if (!isValidDateTime(createdAt) || !isValidDateTime(updatedAt)) throw bad('dates');
  return { id: raw.id, name: raw.name, nameKey: nameKey(raw.name), category, isArchived, createdAt, updatedAt };
}

function checkBar(raw: unknown, index: number): Bar {
  const bad = (what: string) => new BackupFormatError('INVALID', `bar ${index + 1}: ${what}`);
  if (!isRecord(raw)) throw bad('not an object');
  if (!isStr(raw.id) || raw.id.length === 0) throw bad('id');
  if (!isStr(raw.name) || raw.name.trim().length === 0) throw bad('name');
  const { isArchived, createdAt, updatedAt } = raw;
  if (typeof isArchived !== 'boolean') throw bad('isArchived');
  if (!isValidDateTime(createdAt) || !isValidDateTime(updatedAt)) throw bad('dates');
  return { id: raw.id, name: raw.name, nameKey: nameKey(raw.name), isArchived, createdAt, updatedAt };
}

function checkPhotoMeta(raw: unknown, index: number): BackupPhotoMeta {
  const bad = (what: string) => new BackupFormatError('INVALID', `photo ${index + 1}: ${what}`);
  if (!isRecord(raw)) throw bad('not an object');
  if (!isStr(raw.id) || !SAFE_ID.test(raw.id)) throw bad('id');
  if (!isNum(raw.width) || !isNum(raw.height) || !isNum(raw.size)) throw bad('size');
  return {
    id: raw.id, mime: 'image/jpeg', size: raw.size, width: raw.width, height: raw.height,
    createdAt: isValidDateTime(raw.createdAt) ? raw.createdAt : new Date(0).toISOString(),
  };
}

/** Pass 1, part 2: every rule on `data.json`. Throws BackupFormatError naming the first problem; writes nothing. */
export function validateBackupData(raw: unknown, manifest: BackupManifest): BackupData {
  if (!isRecord(raw) || !Array.isArray(raw.entries) || !Array.isArray(raw.tags) || !Array.isArray(raw.photos)) {
    throw new BackupFormatError('INVALID', 'data.json');
  }
  const rawBars: unknown = raw.bars === undefined ? [] : raw.bars; // backups from before the Bar library have none
  if (!Array.isArray(rawBars)) throw new BackupFormatError('INVALID', 'bars');
  if (raw.entries.length > MAX_ROWS || raw.tags.length > MAX_ROWS || raw.photos.length > MAX_ROWS || rawBars.length > MAX_ROWS) {
    throw new BackupFormatError('INVALID', 'too many rows');
  }
  if (raw.entries.length !== manifest.counts.entries || raw.tags.length !== manifest.counts.tags || raw.photos.length !== manifest.counts.photos) {
    throw new BackupFormatError('INVALID', 'counts do not match');
  }

  const tags = raw.tags.map(checkTag);
  const tagById = new Map<string, Tag>();
  const tagKeys = new Set<string>();
  for (const tag of tags) {
    if (tagById.has(tag.id)) throw new BackupFormatError('INVALID', 'duplicate tag id');
    const key = `${tag.category}|${tag.nameKey}`;
    if (tagKeys.has(key)) throw new BackupFormatError('INVALID', `duplicate tag "${tag.name}"`);
    tagById.set(tag.id, tag);
    tagKeys.add(key);
  }

  const bars = rawBars.map(checkBar);
  const barIds = new Set<string>();
  const barKeys = new Set<string>();
  for (const bar of bars) {
    if (barIds.has(bar.id)) throw new BackupFormatError('INVALID', 'duplicate bar id');
    if (barKeys.has(bar.nameKey)) throw new BackupFormatError('INVALID', `duplicate bar "${bar.name}"`);
    barIds.add(bar.id);
    barKeys.add(bar.nameKey);
  }

  const photos = raw.photos.map(checkPhotoMeta);
  const photoIds = new Set<string>();
  for (const photo of photos) {
    if (photoIds.has(photo.id)) throw new BackupFormatError('INVALID', 'duplicate photo id');
    photoIds.add(photo.id);
  }

  const entries: DrinkEntry[] = [];
  const entryIds = new Set<string>();
  raw.entries.forEach((item, i) => {
    const problems = validateEntry(item, { stamps: true });
    if (problems.length > 0) throw new BackupFormatError('INVALID', `entry ${i + 1}: ${problems.map((p) => p.field).join(', ')}`);
    const e = item as DrinkEntry;
    if (!isValidDayKey(e.dayKey)) throw new BackupFormatError('INVALID', `entry ${i + 1}: dayKey`);
    if (entryIds.has(e.id)) throw new BackupFormatError('INVALID', 'duplicate entry id');
    entryIds.add(e.id);
    if (e.photoId !== null && !photoIds.has(e.photoId)) throw new BackupFormatError('INVALID', `entry ${i + 1}: its photo is not in the backup`);
    for (const id of e.baseSpiritTagIds) if (tagById.get(id)?.category !== 'BASE_SPIRIT') throw new BackupFormatError('INVALID', `entry ${i + 1}: unknown tag`);
    for (const id of e.ingredientTagIds) if (tagById.get(id)?.category !== 'INGREDIENT') throw new BackupFormatError('INVALID', `entry ${i + 1}: unknown tag`);
    entries.push({
      id: e.id, drinkName: e.drinkName, category: e.category, dateTime: e.dateTime, dayKey: e.dayKey, barName: e.barName,
      photoId: e.photoId, baseSpiritTagIds: [...e.baseSpiritTagIds], ingredientTagIds: [...e.ingredientTagIds],
      alcoholPercentage: e.alcoholPercentage, alcoholVolumeMl: e.alcoholVolumeMl, notes: e.notes,
      isFavourite: e.isFavourite, createdAt: e.createdAt, updatedAt: e.updatedAt,
    });
  });
  return { entries, tags, bars, photos };
}

/**
 * Pass 1 over a backup file. NO WRITES: reads the ZIP, validates manifest and data.json, and checks that every
 * photo an entry uses is present, intact (CRC) and a JPEG. Throws BackupFormatError.
 */
export async function openBackup(file: Blob, onProgress?: (done: number, total: number) => void): Promise<OpenedBackup> {
  try {
    const zip = await ZipReader.open(file);
    const files = listBackupFiles(zip.entries);
    const manifestEntry = files.get('manifest.json');
    const dataEntry = files.get('data.json');
    if (!manifestEntry || !dataEntry) throw new BackupFormatError('NOT_A_BACKUP', 'manifest.json or data.json is missing');

    const manifest = parseManifest(parseJson(await zip.read(manifestEntry, MAX_MANIFEST), 'manifest.json'));
    const data = validateBackupData(parseJson(await zip.read(dataEntry, MAX_DATA), 'data.json'), manifest);

    const used = [...new Set(data.entries.flatMap((e) => (e.photoId ? [e.photoId] : [])))];
    const readPhoto = async (id: string): Promise<Uint8Array> => {
      const entry = files.get(photoFileName(id));
      if (!entry) throw new BackupFormatError('MISSING_PHOTO', id);
      try {
        return await zip.read(entry, MAX_PHOTO);
      } catch (err) {
        throw toFormatError(err);
      }
    };
    let photoBytes = 0;
    for (let i = 0; i < used.length; i++) {
      const bytes = await readPhoto(used[i]);
      if (bytes.length < 4 || bytes[0] !== 0xff || bytes[1] !== 0xd8 || bytes[2] !== 0xff) throw new BackupFormatError('DAMAGED', 'a photo is not a JPEG');
      photoBytes += bytes.length;
      onProgress?.(i + 1, used.length);
    }
    return { manifest, data, readPhoto, photoBytes };
  } catch (err) {
    throw toFormatError(err);
  }
}

function toFormatError(err: unknown): unknown {
  if (err instanceof BackupFormatError || !(err instanceof ZipError)) return err;
  if (err.code === 'NOT_ZIP') return new BackupFormatError('NOT_A_BACKUP', err.message);
  if (err.code === 'UNSUPPORTED') return new BackupFormatError('UNREADABLE', err.message);
  return new BackupFormatError('DAMAGED', err.message);
}
